const {contextBridge,ipcRenderer}=require('electron')
contextBridge.exposeInMainWorld('dBotDesktop',Object.freeze({
  state:()=>ipcRenderer.invoke('desktop:state'),
  showMain:()=>ipcRenderer.invoke('desktop:show'),
  hideMain:()=>ipcRenderer.invoke('desktop:hide'),
  togglePet:()=>ipcRenderer.invoke('desktop:toggle-pet'),
  setPanel:open=>ipcRenderer.invoke('desktop:panel',Boolean(open)),
  setRoaming:value=>ipcRenderer.invoke('desktop:roaming',Boolean(value)),
  setClickThrough:value=>ipcRenderer.invoke('desktop:click-through',Boolean(value)),
  setPetMood:value=>ipcRenderer.invoke('desktop:pet-mood',value),
  previewPetMood:value=>ipcRenderer.invoke('desktop:preview-mood',value),
  move:(dx,dy)=>ipcRenderer.send('desktop:move',{dx,dy}),
  menu:()=>ipcRenderer.invoke('desktop:menu'),
  command:(text,context={})=>ipcRenderer.invoke('desktop:command',text,context),
  completeAction:id=>ipcRenderer.invoke('desktop:complete-action',id),
  prepareVoice:()=>ipcRenderer.invoke('desktop:prepare-voice'),
  setVoiceSpeed:value=>ipcRenderer.invoke('desktop:voice-speed',value),
  ask:(text,source='text')=>ipcRenderer.invoke('desktop:ask',text,source),
  cancel:()=>ipcRenderer.invoke('desktop:cancel'),
  transcribe:(bytes,language)=>ipcRenderer.invoke('desktop:transcribe',bytes,language),
  speak:(text,speed)=>ipcRenderer.invoke('desktop:speak',text,speed),
  onReply:callback=>{const fn=(_event,value)=>callback(value);ipcRenderer.on('desktop:reply',fn);return ()=>ipcRenderer.removeListener('desktop:reply',fn)},
  onState:callback=>{const fn=(_event,state)=>callback(state);ipcRenderer.on('desktop:state-update',fn);return ()=>ipcRenderer.removeListener('desktop:state-update',fn)},
}))
